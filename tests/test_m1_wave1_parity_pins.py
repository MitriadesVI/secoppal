def test_a_new_member_after_control_language_passes_and_anything_else_fails():
    source = index_source(SEMANTIC_DIMENSIONS)
    assert semantic_dimensions_problems(source) == []
    cls_tail = source.rstrip("\n") + "\n"
    for good in ('    FOO = "FOO"\n', '    # a comment\n    FOO = "FOO"\n    BAR = "BAR"\n'):
        assert semantic_dimensions_problems(cls_tail + good) == [], good
    for bad in ("def helper():\n    return 1\n",              # after the class: not main's bytes
                "    def helper(self):\n        return 1\n",   # inside the class
                '    FOO = "BAR"\n',                           # name and value differ
                '    TOPIC = "TOPIC"\n',                       # a main member re-declared
                '    FOO = "FOO"  # trailing comment\n'):
        assert semantic_dimensions_problems(cls_tail + bad), bad
    assert semantic_dimensions_problems(source.replace('STATE = "STATE"', 'STATE = "STATE "')), "a changed main member"
    assert semantic_dimensions_problems(source.replace('    VALUE = "VALUE"\n', '    FOO = "FOO"\n    VALUE = "VALUE"\n'))



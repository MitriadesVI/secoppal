@functools.lru_cache(maxsize=1)
def legacy_manifest() -> dict[str, str]:
    return json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))


def _relative(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def _sha_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _module_bytes(name: str, index: dict[str, Path], overrides: dict[str, str] | None) -> bytes:
    if overrides and name in overrides:
        return overrides[name].encode("utf-8")
    return index[name].read_bytes()


def frozen_module_problems(overrides: dict[str, str] | None = None) -> list[str]:
    """Modules of the legacy closure whose sha is not the manifest's (``overrides`` replace sources in memory)."""
    index, graph, _ = build_graph(overrides)
    manifest = legacy_manifest()
    out = []
    for name in sorted(closure(graph)):
        relative = _relative(index[name])
        if relative not in manifest:
            out.append(f"{name}: not in the manifest of main (a module the legacy closure did not have)")
            continue
        sha = _sha_bytes(_module_bytes(name, index, overrides))
        if name in LEAF_SHA256:
            if sha != LEAF_SHA256[name]:
                out.append(f"{name}: differs from its pinned source-boundary leaf")
        elif name not in ALLOWED_DIVERGENCE and sha != manifest[relative]:
            out.append(f"{name}: differs from main 88653752")
    return out


@functools.lru_cache(maxsize=1)
def data_extensions() -> tuple[str, ...]:
    """Every extension a versioned non-``.py`` file of main has (``.json`` ``.txt`` ``.md`` ``.gz`` ``.log`` ...)
    plus the data formats a reader may name even if none is versioned (D1(d), spec v3 pin 3(b))."""
    found = {posixpath.splitext(path)[1].lower() for path in legacy_manifest() if not path.endswith(".py")}
    return tuple(sorted({ext for ext in found if re.fullmatch(r"\.[a-z0-9]{1,8}", ext)} | set(EXTRA_DATA_EXTENSIONS)))


@functools.lru_cache(maxsize=1)
def _manifest_dirs() -> frozenset[str]:
    out = set()
    for path in legacy_manifest():
        parent = posixpath.dirname(path)
        while parent and parent not in out:
            out.add(parent)
            parent = posixpath.dirname(parent)
    return frozenset(out)


def _app_data_paths() -> list[str]:
    return [path for path in legacy_manifest() if path.startswith(DATA_ROOT + "/")]


@functools.lru_cache(maxsize=None)
def _string_literals(source: str) -> tuple[tuple[int, str], ...]:
    return tuple((node.lineno, node.value) for node in ast.walk(ast.parse(source))
                 if isinstance(node, ast.Constant) and isinstance(node.value, str))


def data_literals(source: str) -> list[tuple[int, str]]:
    """Every string literal that ends like a data file of main (any versioned data extension)."""
    suffixes = data_extensions()
    return [(lineno, value) for lineno, value in _string_literals(source) if value.endswith(suffixes)]


def directory_literals(source: str) -> list[tuple[int, str]]:
    """Multi-segment path literals without a data extension: candidates for a data DIRECTORY (``data/conversations``)."""
    suffixes = data_extensions()
    return [(lineno, value) for lineno, value in _string_literals(source)
            if "/" in value.strip("/") and not value.startswith("/") and "://" not in value
            and not re.search(r"\s", value) and not value.endswith(suffixes)]


def _anchors(module_relative: str) -> list[str]:
    """The module's directory and every ancestor up to the repository root, then ``app/data`` (the ``DATA / name``
    idiom of the closure)."""
    bases, base = [], posixpath.dirname(module_relative)
    while True:
        bases.append(base)
        if not base:
            break
        base = posixpath.dirname(base)
    return [*bases, DATA_ROOT]


def resolve_data_literal(module_relative: str, literal: str) -> tuple[str, ...]:
    """The versioned files of main that ``literal`` names from ``module_relative``, by RESOLVED path, never by bare
    name. Rules in order, the first that finds something decides:

    1. relative to the repository root (``artifacts/audits/municipal_m2a/logical_units.json``);
    2. relative to the module (its directory or any ancestor, or ``app/data``: ``Path(__file__)…/"data"/…``);
    3. as the UNIQUE suffix of a versioned path (more than one match is returned whole: the caller flags it).

    An empty result is an unresolved literal.
    """
    manifest = legacy_manifest()
    name = posixpath.normpath(literal.removeprefix("./"))
    found = [name] if name in manifest else []
    for anchor in _anchors(module_relative):
        resolved = posixpath.normpath(posixpath.join(anchor, name))
        if resolved in manifest and resolved not in found:
            found.append(resolved)
    if found:
        return tuple(found)
    if not name.startswith("/"):
        return tuple(sorted(path for path in manifest if path.endswith("/" + name)))
    return ()


def resolve_data_directory(module_relative: str, literal: str) -> tuple[str, ...]:
    """The versioned directories of main a path literal names (rules 1 and 2; a suffix of a directory is not a name)."""
    name = posixpath.normpath(literal)
    candidates = {name} | {posixpath.normpath(posixpath.join(anchor, name)) for anchor in _anchors(module_relative)}
    return tuple(sorted(candidate for candidate in candidates if candidate in _manifest_dirs()))


def closure_data_reads(overrides: dict[str, str] | None = None) -> list[tuple[str, int, str, str, tuple[str, ...]]]:
    """``(module, line, literal, verdict, files)`` for every data literal of the legacy closure. ``verdict`` is
    ``exempt`` | ``frozen`` | ``ambiguous`` | ``unresolved``; ``files`` are the versioned files that must stay as at main."""
    manifest = legacy_manifest()
    index, graph, _ = build_graph(overrides)
    out = []
    for name in sorted(closure(graph)):
        source = (overrides or {}).get(name)
        source = index[name].read_text(encoding="utf-8") if source is None else source
        relative = _relative(index[name])
        for lineno, literal in sorted(data_literals(source)):
            matched = resolve_data_literal(relative, literal)
            if (name, literal) in NON_DATA_LITERALS:
                out.append((name, lineno, literal, "exempt", ()))
            elif not matched:
                out.append((name, lineno, literal, "unresolved", ()))
            elif len(matched) > 1:
                out.append((name, lineno, literal, "ambiguous", matched))
            else:
                out.append((name, lineno, literal, "frozen", matched))
        for lineno, literal in sorted(directory_literals(source)):
            directories = resolve_data_directory(relative, literal)
            if not directories or (name, literal) in NON_DATA_LITERALS:
                continue
            files = tuple(sorted(path for path in manifest if any(path.startswith(d + "/") for d in directories)))
            out.append((name, lineno, literal, "ambiguous" if len(directories) > 1 else "frozen", files))
    return out


@functools.lru_cache(maxsize=1)
def _closure_data_paths() -> tuple[str, ...]:
    return tuple(sorted({path for *_, verdict, files in closure_data_reads() if verdict == "frozen" for path in files}))


def disk_data_files() -> dict[str, bytes]:
    """``app/data/**`` as it is on disk (a new file is a violation) and every other versioned file the closure
    reads that exists."""
    files = {_relative(path): path.read_bytes() for path in sorted((ROOT / DATA_ROOT).rglob("*"))
             if path.is_file() and "__pycache__" not in path.parts}
    for path in _closure_data_paths():
        if (ROOT / path).is_file():
            files[path] = (ROOT / path).read_bytes()
    return files


def frozen_data_problems(overrides: dict[str, str] | None = None,
                         data_files: dict[str, bytes] | None = None) -> list[str]:
    """D1(d): ``app/data/**`` and every versioned file the legacy closure reads are byte-frozen; no new file under
    ``app/data``; nothing of ``host_data``; every data literal resolves, unambiguously, or is exempt with a reason.
    ``data_files`` replaces the disk content of some files in memory."""
    manifest = legacy_manifest()
    files = disk_data_files() if data_files is None else data_files
    reads = closure_data_reads(overrides)
    needed = set(_app_data_paths()) | {path for *_, verdict, found in reads if verdict == "frozen" for path in found}
    out = []
    for path in sorted(needed | set(files)):
        if path not in manifest:
            out.append(f"{path}: a NEW file under {DATA_ROOT}/ (corrections go to app/host_data/<dim>/)")
            continue
        data = files.get(path)
        if data is None and data_files is None and (ROOT / path).is_file():  # a file only an override reads
            data = (ROOT / path).read_bytes()
        if data is None:
            out.append(f"{path}: frozen data file is gone")
        elif _sha_bytes(data) != manifest[path]:
            out.append(f"{path}: differs from main 88653752")
    for name, lineno, literal, verdict, found in reads:
        if verdict == "unresolved":
            out.append(f"{name}:{lineno}: names {literal!r}, which resolves to no frozen data file of main")
        elif verdict == "ambiguous":
            out.append(f"{name}:{lineno}: names {literal!r}, which is ambiguous ({len(found)} versioned matches)")
    index, graph, _ = build_graph(overrides)
    for name in sorted(closure(graph)):
        source = (overrides or {}).get(name)
        source = index[name].read_text(encoding="utf-8") if source is None else source
        if "host_data" in source:
            out.append(f"{name}: legacy reaches host_data (the citation route's data)")
    return out


def _tail_problems(lines: list[str]) -> list[str]:
    out = []
    for line in lines:
        text = line.strip()
        if not text or text.startswith("#"):
            continue
        match = re.fullmatch(r'    ([A-Z][A-Z0-9_]*) = "([A-Z][A-Z0-9_]*)"', line.rstrip("\n"))
        if match is None or match[1] != match[2] or match[1] in MAIN_MEMBERS:
            out.append(f"not a new NAME = \"NAME\" member: {line.rstrip()!r}")
    return out


def semantic_dimensions_problems(source: str) -> list[str]:
    """Pin 4: ``source`` minus the trailing block after ``CONTROL_LANGUAGE`` must be main's bytes; the block
    itself holds only blank lines, comments and new ``NAME = "NAME"`` members."""
    tree = ast.parse(source)
    cls = next(node for node in tree.body if isinstance(node, ast.ClassDef) and node.name == "SemanticDimension")
    last = next(node for node in cls.body if isinstance(node, ast.Assign)
                and any(isinstance(t, ast.Name) and t.id == "CONTROL_LANGUAGE" for t in node.targets))
    lines = source.splitlines(keepends=True)
    tail = lines[last.end_lineno:cls.end_lineno]
    kept = "".join(lines[:last.end_lineno] + lines[cls.end_lineno:])
    out = _tail_problems(tail)
    if _sha_bytes(kept.encode("utf-8")) != legacy_manifest()["app/core/semantic_dimensions.py"]:
        out.append("the file minus the trailing member block is not main's semantic_dimensions.py")
    return out


def _annotation_nodes(tree: ast.AST) -> set[int]:
    roots = []
    for node in ast.walk(tree):
        if isinstance(node, ast.AnnAssign):
            roots.append(node.annotation)
        elif isinstance(node, ast.arg) and node.annotation is not None:
            roots.append(node.annotation)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.returns is not None:
            roots.append(node.returns)
    return {id(inner) for root in roots for inner in ast.walk(root)}


def semantic_dimension_use_problems(source: str) -> list[str]:
    """Pin 5: legacy may only NAME a main member of ``SemanticDimension`` (or use the type in an annotation)."""
    tree = ast.parse(source)
    names = {"SemanticDimension"}
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and (node.module or "").endswith("semantic_dimensions"):
            names |= {alias.asname for alias in node.names if alias.name == "SemanticDimension" and alias.asname}
    parents = {id(child): parent for parent in ast.walk(tree) for child in ast.iter_child_nodes(parent)}
    annotated = _annotation_nodes(tree)
    out = []
    for node in ast.walk(tree):
        named = (isinstance(node, ast.Name) and node.id in names) or (
            isinstance(node, ast.Attribute) and node.attr == "SemanticDimension")
        if not named or id(node) in annotated:
            continue
        parent = parents.get(id(node))
        if isinstance(parent, ast.Attribute) and parent.value is node and parent.attr in MAIN_MEMBERS:
            continue
        out.append(f"line {node.lineno}: SemanticDimension used other than as a main member or an annotation")
    return out


class _Bare(ast.NodeTransformer):
    """Drops type annotations: the leaf holds the guard as an opaque ``object`` (it cannot import its class)."""

    def visit_arg(self, node: ast.arg) -> ast.arg:
        node.annotation = None
        return node

    def visit_FunctionDef(self, node: ast.FunctionDef) -> ast.FunctionDef:
        self.generic_visit(node)
        node.returns = None
        return node

    def visit_AnnAssign(self, node: ast.AnnAssign) -> ast.AST:
        self.generic_visit(node)
        if node.value is None:
            return ast.Pass()
        return ast.Assign(targets=[node.target], value=node.value)


def _leaf_definitions(tree: ast.Module, name: str) -> list[str]:
    """``ast.dump`` of every top-level definition or assignment of ``name``, annotations removed."""
    found = []
    for node in tree.body:
        targets = []
        if isinstance(node, ast.Assign):
            targets = [t.id for t in node.targets if isinstance(t, ast.Name)]
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            targets = [node.target.id]
        if (isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == name) or name in targets:
            found.append(ast.dump(_Bare().visit(copy.deepcopy(node))))
    return found


def leaf_ast_problems(source: str) -> list[str]:
    """Pin 6(c): the six functions and the two ``ContextVar`` of the leaf are main's, by AST, annotations aside."""
    reference = LEAF_MAIN_SOURCE.read_bytes()
    out = []
    if _sha_bytes(reference) != legacy_manifest()["app/core/foundation_guard.py"]:
        out.append("the fixture is not main's foundation_guard.py (its sha is not the manifest's)")
    main, mine = ast.parse(reference.decode("utf-8")), ast.parse(source)
    for name in (*LEAF_FUNCTIONS, *LEAF_ASSIGNMENTS):
        expected = _leaf_definitions(main, name)
        if not expected:
            out.append(f"{name}: not defined in main's source")
        elif _leaf_definitions(mine, name) != expected:
            out.append(f"{name}: its AST is not main's")
    return out



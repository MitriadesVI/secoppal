def test_applies_to_is_a_live_aspect_of_the_comparison(monkeypatch):
    wrongs = []
    for i in range(len(DUAL_REFERENCE["effective"]["conditions"])):
        wrong = copy.deepcopy(DUAL_REFERENCE)
        wrong["effective"]["conditions"][i]["request_ids"] = wrong["effective"]["conditions"][i]["request_ids"][:1]
        wrongs.append(wrong)

    def no_applies_to(p):
        if p is None or "conditions" not in p:
            return p
        return {**p, "conditions": sorted(({**c, "applies_to": None} if "carried" in c else
                                           {"new": {**c["new"], "applies_to": None}} for c in p["conditions"]), key=gold.canon)}

    monkeypatch.setattr(oracle, "effective_equal", lambda have, want: no_applies_to(have) == no_applies_to(want))
    assert all(run_audit(DUAL, wrong)["ok"] for wrong in wrongs)



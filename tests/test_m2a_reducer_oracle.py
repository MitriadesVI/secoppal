def _decision(gid="SF075", owner="FOUNDATION_O1B_EXPLICIT_TIME_PARITY", doc=RECORD, decision_id="UD-2026-10-02-SF075", sha=None):
    return {"owner": owner, "decided_by": "user", "date": "2026-10-02",
            "record": {"doc": doc, "decision_id": decision_id,
                       "doc_sha256": sha or hashlib.sha256((ROOT / RECORD).read_bytes()).hexdigest()}}


def _write(file, decisions):
    file.write_text(json.dumps({"schema": gold.DECISIONS_SCHEMA, "decisions": decisions}), encoding="utf-8")



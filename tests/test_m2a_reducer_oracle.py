# ---- the comparison is not vacuous: neutralise one aspect and exactly its mutants get through ----------------------------------
def _map_new(projection, fn):
    if projection is None or "conditions" not in projection:
        return projection
    return {**projection, "conditions": sorted(
        ({"new": fn(dict(c["new"]))} if "new" in c else c for c in projection["conditions"]), key=gold.canon)}


def _no_polarity(new):
    return {**new, "polarity": None, "slot": new["slot"].replace("/NEGATIVE", "/POSITIVE"),
            "value": [i.replace("excluded=1", "excluded=0") for i in new["value"]]}


def _no_value_side(new):
    if new["dimension"] != "VALUE":
        return new
    return {**new, "operator": None, "slot": "VALUE", "value": new["value"][:2]}


def _no_conditions(p):
    return p if p is None or "conditions" not in p else {**p, "conditions": []}


def _as_a_set(p):
    return p if p is None or "conditions" not in p else {**p, "conditions": sorted(
        {gold.canon(c): c for c in p["conditions"]}.values(), key=gold.canon)}


COMPARISON_ASPECTS = {  # aspect -> (a weakened projection, the mutants that depend on exactly that aspect)
    "conditions": (_no_conditions, {"drop_carried", "drop_condition", "add_condition", "flip_value_side", "invert_polarity",
                                    "change_value", "partial_application", "wrong_unit", "wrong_direction_source",
                                    "duplicate_condition", "effective_missing"}),
    "requests": (lambda p: p if p is None or "requests" not in p else {**p, "requests": []},
                 {"swap_universe", "swap_universe_kind"}),
    "logic": (lambda p: p if p is None or "logic" not in p else {**p, "logic": None}, {"logic_present"}),
    "polarity": (lambda p: _map_new(p, _no_polarity), {"invert_polarity"}),
    "value_side": (lambda p: _map_new(p, _no_value_side), {"flip_value_side"}),
    "value": (lambda p: _map_new(p, lambda n: {**n, "value": n["value"][:1]}), {"change_value"}),
    "multiplicity": (_as_a_set, {"duplicate_condition"}),
    "placed_unchanged": (lambda p: _map_new(p, lambda n: {**n, "from_patch": None}),
                         {f"tamper_new_{f}" for f in IDENTITY_FIELDS}),
}


@pytest.mark.parametrize("aspect", sorted(COMPARISON_ASPECTS))
def test_neutralising_an_aspect_of_the_comparison_lets_exactly_its_mutants_through(aspect, monkeypatch):
    weakened, operators = COMPARISON_ASPECTS[aspect]
    monkeypatch.setattr(oracle, "effective_equal", lambda have, want: weakened(have) == weakened(want))
    survived = {name for gid, name, actual in all_mutants() if run_audit(BY_ID[gid], actual)["ok"]}
    assert survived, f"{aspect}: no mutant depends on it, so the check is vacuous"
    if aspect != "conditions":
        assert survived <= operators, (aspect, sorted(survived - operators))
    else:  # without conditions every condition-level mutant survives, and nothing else
        assert survived <= operators | {n for _, n, _ in all_mutants() if n.startswith("tamper_")}



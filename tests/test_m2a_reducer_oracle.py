FORBIDDEN_MODULE_NAMES = ("foundation_accepted", "foundation_delta", "foundation_turn_scope", "foundation_admission",
                          "foundation_runtime")
ALLOWED_APP_MODULES = frozenset({"app.core.foundation_authority_values", "app.core.foundation_geo_level"})
